import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('purchase details match the approved mock and preserve exact copy costs and safe navigation', async ({ page, context }) => {
  const writes: string[] = [];
  page.on('request', r => { if (/firestore|workers\.dev/.test(r.url())) writes.push(r.url()); });
  await page.goto('./#/transactions/history?transactions=sample');
  await expect(page.locator('.history-kind-label').first()).toHaveCSS('font-weight', '700');
  await expect(page.locator('.history-total').first()).toHaveCSS('font-weight', '700');
  await expect(page.getByRole('heading', { name: 'November 2026' })).toHaveCSS('font-weight', '700');
  await page.getByRole('button', { name: /View transaction: sample-nov-19/ }).click();
  await expect(page.getByRole('heading', { name: 'Purchase details', exact: true })).toBeVisible();
  await expect(page.getByRole('navigation', { name: 'Section navigation' })).toHaveCount(0);
  const nav = page.getByRole('navigation', { name: 'Main navigation' });
  await expect(nav).toBeVisible();
  await expect(nav.getByRole('link', { name: 'Transactions', exact: true })).toHaveAttribute('aria-current', 'page');
  await expect(page.getByRole('heading', { name: 'eBay · cardcorner' })).toBeVisible();
  await expect(page.getByText('Shipping: $4.00 per copy')).toBeVisible();
  await expect(page.getByText('$142.00', { exact: true })).toBeVisible();
  await expect(page.locator('.purchase-card-name').first()).toHaveCSS('font-weight', '700');
  await expect(page.locator('.purchase-total')).toHaveCSS('font-weight', '700');
  await page.evaluate(() => document.fonts.ready);
  await page.locator('.pokemon-art img').evaluateAll(imgs => Promise.all(imgs.map(img => (img as HTMLImageElement).decode().catch(() => undefined))));
  await page.screenshot({ path: test.info().outputPath('purchase-details-en.png') });
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.getByRole('button', { name: /^Gengar/ }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByText('$46.00', { exact: true })).toBeVisible();
  await expect(dialog.getByText('$50.00', { exact: true })).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Edit copy' })).toBeDisabled();
  await dialog.getByRole('button', { name: 'View purchase' }).click();
  await expect(dialog).toHaveCount(0);
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.getByRole('button', { name: /^Copy tracking number/ }).click();
  await expect(page.getByRole('status')).toHaveText('Tracking number copied');
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('DEMO-RM00004821GB');
  await page.getByRole('button', { name: 'Back to History' }).click();
  await expect(page).toHaveURL(/transactions\/history\?transactions=sample$/);
  await page.goto('./#/transactions/purchases/sample-nov-19?transactions=sample');
  for (const width of [320, 390, 768]) {
    await page.setViewportSize({ width, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByText('Tracking number received', { exact: true }).evaluate(el => el.scrollIntoView({ block: 'center' }));
    const last = await page.getByText('Tracking number received', { exact: true }).boundingBox();
    const bar = await nav.boundingBox();
    expect(last!.y + last!.height).toBeLessThanOrEqual(bar!.y);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Back to History' }).click();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'עברית', exact: true }).click();
  await page.getByRole('button', { name: 'סגירה', exact: true }).click();
  await page.getByRole('button', { name: /הצגת עסקה: sample-nov-19/ }).click();
  await expect(page.getByRole('heading', { name: 'פרטי רכישה', exact: true })).toBeVisible();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: test.info().outputPath('purchase-details-he.png') });
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.goto('./#/transactions/purchases/sample-nov-19');
  await expect(page.getByRole('heading', { name: 'Purchase unavailable' })).toBeVisible();
  await page.getByRole('button', { name: 'Back to History', exact: true }).first().click();
  await expect(page.getByRole('listitem')).toHaveCount(0);
  await page.goto('./#/transactions/purchases/absent?transactions=sample');
  await expect(page.getByRole('heading', { name: 'Purchase unavailable' })).toBeVisible();
  expect(writes).toEqual([]);
});
