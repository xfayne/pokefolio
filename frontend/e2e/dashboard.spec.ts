 expect(Math.abs((await page.locator('.dashboard-big').boundingBox())!.y-baseline!.y)).toBeLessThan(1);
 expect(Math.abs((await page.locator('.dashboard-metric-kpis').boundingBox())!.y-originalKpis!.y)).toBeLessThan(1);
