test('dashboard stays within narrow viewports and supports Hebrew and reduced motion',async({page})=>{
 await page.clock.setFixedTime(new Date('2026-11-21T12:00:00Z'));
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.goto('./#/dashboard?dashboard=sample');
 await expect(page.locator('.dashboard-chart-line').first()).toHaveCSS('animation-name','none');
 await expect(page.locator('.dashboard-chart-fill').first()).toHaveCSS('opacity','1');
 await expect(page.locator('.dashboard-metric-kpis')).toHaveCSS('animation-name','none');
 for(const width of [320,390,768,1280]){
  await page.setViewportSize({width,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.evaluate(()=>window.scrollTo(200,window.scrollY));
  expect(await page.evaluate(()=>window.scrollX)).toBe(0);
  await expect(page.locator('html')).toHaveCSS('overscroll-behavior-x','none');
 }
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByRole('button',{name:'עברית',exact:true}).click();
 await page.getByRole('button',{name:'סגירה',exact:true}).click();
 await expect(page.getByRole('heading',{name:'שווי האוסף'})).toBeVisible();
 await expect(page.locator('html')).toHaveAttribute('dir','rtl');
 await page.evaluate(()=>document.fonts.ready);
 await page.screenshot({path:test.info().outputPath('dashboard-top-he.png')});
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
});

