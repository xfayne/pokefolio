import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('new purchase follows the mock and saves only pending demo copies with reconciled amounts', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const writes: string[] = [];
  page.on('request', r => { if (/firestore|workers\.dev/.test(r.url())) writes.push(r.url()); });
  await page.goto('./#/transactions/history?transactions=sample');
  await page.getByRole('button', { name: 'New transaction', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'New transaction', exact: true })).toBeVisible();
  await expect(page.getByText('$142.00', { exact: true })).toBeVisible();
  await expect(page.getByText('Split equally: $4.00 per copy')).toBeVisible();
  const shipment = page.getByRole('button', { name: 'Shipment details (optional)' });
  await expect(shipment).toHaveAttribute('aria-expanded', 'false');
  await expect(page.getByRole('button', { name: 'Add card', exact: true })).toHaveAttribute('aria-disabled', 'true');
  await page.evaluate(() => document.fonts.ready);
  await page.locator('.pokemon-art img').evaluateAll(imgs => Promise.all(imgs.map(img => (img as HTMLImageElement).decode().catch(() => undefined))));
  await page.screenshot({ path: test.info().outputPath('new-purchase-en.png') });
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  for (const width of [320, 390, 768]) {
    await page.setViewportSize({ width, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(await page.getByLabel('Card cost 1', { exact: true }).evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(16);
    await shipment.evaluate(el => el.scrollIntoView({ block: 'center' }));
    const panel = await shipment.boundingBox(), save = await page.locator('.new-purchase-save').boundingBox();
    expect(panel!.y + panel!.height).toBeLessThanOrEqual(save!.y);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Back to History' }).click();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'עברית', exact: true }).click();
  await page.getByRole('button', { name: 'סגירה', exact: true }).click();
  await page.getByRole('button', { name: 'עסקה חדשה', exact: true }).click();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: test.info().outputPath('new-purchase-he.png') });
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  // Return to English without reloading: drafts survive ordinary route changes.
  await page.getByRole('button', { name: 'חזרה להיסטוריה' }).click();
  await page.getByRole('button', { name: 'הגדרות', exact: true }).click();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('button', { name: 'New transaction', exact: true }).click();
  await page.getByLabel('Card cost 1', { exact: true }).fill('');
  await page.getByRole('button', { name: 'Save purchase', exact: true }).click();
  await expect(page.getByLabel('Card cost 1', { exact: true })).toHaveAttribute('aria-invalid', 'true');
  await page.getByLabel('Card cost 1', { exact: true }).fill('52.00');
  await page.getByLabel('Shipping cost', { exact: true }).fill('10.00');
  await expect(page.getByText('Split equally: $3.33–$3.34 per copy (rounded)')).toBeVisible();
  await page.getByRole('button', { name: 'Save purchase', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Purchase details', exact: true })).toBeVisible();
  await expect(page.getByText('$140.00', { exact: true })).toBeVisible();
  await expect(page.getByText('Pending', { exact: true })).toBeVisible();
  await expect(page.getByText('Payment status unknown', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Back to History' }).click();
  await expect(page.getByRole('listitem')).toHaveCount(5);
  await page.goto('./#/transactions/new');
  await expect(page.getByRole('listitem')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Save purchase', exact: true })).toBeDisabled();
  await page.goto('./#/transactions/history');
  await expect(page.getByRole('listitem')).toHaveCount(0);
  expect(writes).toEqual([]);
});
